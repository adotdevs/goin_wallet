const fs = require("fs");
const path = require("path");
const postcss = require("postcss");
const tailwindcss = require("tailwindcss");
const prefixer = require("postcss-prefix-selector");
const autoprefixer = require("autoprefixer");

const rootDir = path.resolve(__dirname, "..");
const inputPath = path.join(rootDir, "src/jsx/pages/kycPortal/kyc-portal.source.css");
const outputPath = path.join(rootDir, "src/jsx/pages/kycPortal/kyc-portal.css");
const tailwindConfigPath = path.join(rootDir, "tailwind.kyc.config.js");

async function buildKycCss() {
  const css = fs.readFileSync(inputPath, "utf8");

  const result = await postcss([
    tailwindcss(tailwindConfigPath),
    prefixer({
      prefix: "#kyc-portal",
      transform(prefix, selector, prefixedSelector) {
        const trimmed = selector.trim();

        // Keep explicit portal-scoped and html-active selectors untouched
        if (
          trimmed.startsWith("#kyc-portal") ||
          trimmed.startsWith("html.kyc-portal-active")
        ) {
          return trimmed;
        }

        // Map Tailwind preflight root/html/body selectors onto #kyc-portal itself
        if (
          trimmed === "html" ||
          trimmed === "body" ||
          trimmed === ":root" ||
          trimmed === ":host"
        ) {
          return prefix;
        }

        if (trimmed.startsWith("html ") || trimmed.startsWith("body ")) {
          return trimmed.replace(/^(html|body)\s+/, `${prefix} `);
        }

        // Pseudo-elements like ::before, ::after, ::backdrop, ::placeholder
        if (trimmed.startsWith("::") || trimmed.startsWith(":-")) {
          return `${prefix} ${trimmed}`;
        }

        return prefixedSelector;
      },
    }),
    autoprefixer(),
  ]).process(css, { from: inputPath, to: outputPath });

  const banner =
    "/* AUTO-GENERATED by scripts/build-kyc-css.js from kyc-portal.source.css — do not edit directly */\n";
  fs.writeFileSync(outputPath, banner + result.css, "utf8");
  console.log(
    `[build-kyc-css] Wrote ${path.relative(rootDir, outputPath)} (${(
      result.css.length / 1024
    ).toFixed(1)} KB)`
  );
}

buildKycCss().catch((err) => {
  console.error("[build-kyc-css] Failed:", err);
  process.exit(1);
});
