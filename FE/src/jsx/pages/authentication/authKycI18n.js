export function getAuthKycLang() {
  if (typeof window === "undefined") return "fr";
  try {
    const saved = window.localStorage.getItem(AUTH_KYC_LANG_KEY);
    return saved && TRANSLATIONS[saved] ? saved : "fr";
  } catch {
    return "fr";
  }
}

export function setAuthKycLang(nextLang) {
  if (!TRANSLATIONS[nextLang]) return;
  try {
    window.localStorage.setItem(AUTH_KYC_LANG_KEY, nextLang);
  } catch {
    // ignore storage errors
  }
  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent(LANG_CHANGE_EVENT, { detail: nextLang }));
  }
}

export function useAuthKycLang() {
  const [lang, setLang] = useState(getAuthKycLang);

  useEffect(() => {
    const onCustom = (e) => {
      if (e?.detail && TRANSLATIONS[e.detail]) {
        setLang(e.detail);
      }
    };
    const onStorage = (e) => {
      if (e.key === AUTH_KYC_LANG_KEY && e.newValue && TRANSLATIONS[e.newValue]) {
        setLang(e.newValue);
      }
    };
    window.addEventListener(LANG_CHANGE_EVENT, onCustom);
    window.addEventListener("storage", onStorage);
    return () => {
      window.removeEventListener(LANG_CHANGE_EVENT, onCustom);
      window.removeEventListener("storage", onStorage);
    };
  }, []);

  const changeLang = useCallback((nextLang) => {
    if (!TRANSLATIONS[nextLang]) return;
    setLang(nextLang);
    setAuthKycLang(nextLang);
  }, []);

  const t = TRANSLATIONS[lang] || TRANSLATIONS.fr;
  return { lang, changeLang, t };
}
