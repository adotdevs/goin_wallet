export function translateHomeString(rawText, lang) {
  if (!rawText || lang === "en") return rawText;
  const normalized = rawText.replace(/\s+/g, " ").trim();
  if (!normalized) return rawText;

  const entry = HOME_TEXT_TRANSLATIONS[normalized];
  const translated = entry?.[lang];
  if (!translated) return rawText;

  const leading = rawText.match(/^\s*/)?.[0] || "";
  const trailing = rawText.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}
