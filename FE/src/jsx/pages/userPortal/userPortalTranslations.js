export function translatePortalText(raw, lang) {
  if (!raw || lang === "en") return raw;
  const normalized = raw.replace(/\s+/g, " ").trim();
  if (!normalized) return raw;

  const leading = raw.match(/^\s*/)?.[0] || "";
  const trailing = raw.match(/\s*$/)?.[0] || "";

  const exact = PORTAL_TRANSLATIONS[normalized]?.[lang];
  if (exact) {
    return `${leading}${exact}${trailing}`;
  }

  for (const rule of DYNAMIC_PATTERNS) {
    const match = normalized.match(rule.re);
    if (match && rule[lang]) {
      return `${leading}${rule[lang](...match)}${trailing}`;
    }
  }

  return raw;
}

const TRANSLATABLE_ATTRS = ["placeholder", "title", "aria-label"];

export function applyPortalTranslations(rootEl, lang, state) {
  if (!rootEl) return;

  const { textOriginals, textLastApplied, attrOriginals, attrLastApplied } = state;

  const walker = document.createTreeWalker(rootEl, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      if (parent.closest("script, style, svg, code, pre, [data-no-translate='1']")) {
        return NodeFilter.FILTER_REJECT;
      }
      if (!node.nodeValue || !node.nodeValue.trim()) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  const textNodes = [];
  let cur = walker.nextNode();
  while (cur) {
    textNodes.push(cur);
    cur = walker.nextNode();
  }

  for (const node of textNodes) {
    const currentVal = node.nodeValue;
    const lastApplied = textLastApplied.get(node);

    // If React updated this text node to a brand-new string, refresh its cached English original
    if (!textOriginals.has(node) || (lastApplied !== undefined && currentVal !== lastApplied)) {
      textOriginals.set(node, currentVal);
    }

    const original = textOriginals.get(node);
    const nextVal = translatePortalText(original, lang);
    textLastApplied.set(node, nextVal);
    if (currentVal !== nextVal) {
      node.nodeValue = nextVal;
    }
  }

  const elements = rootEl.querySelectorAll("[placeholder], [title], [aria-label]");
  elements.forEach((el) => {
    if (el.closest("svg, [data-no-translate='1']")) return;
    let origMap = attrOriginals.get(el);
    let appliedMap = attrLastApplied.get(el);
    if (!origMap) {
      origMap = {};
      attrOriginals.set(el, origMap);
    }
    if (!appliedMap) {
      appliedMap = {};
      attrLastApplied.set(el, appliedMap);
    }

    for (const attr of TRANSLATABLE_ATTRS) {
      if (!el.hasAttribute(attr)) continue;
      const curAttr = el.getAttribute(attr) || "";
      if (
        origMap[attr] === undefined ||
        (appliedMap[attr] !== undefined && curAttr !== appliedMap[attr])
      ) {
        origMap[attr] = curAttr;
      }
      const nextAttr = translatePortalText(origMap[attr], lang);
      appliedMap[attr] = nextAttr;
      if (curAttr !== nextAttr) {
        el.setAttribute(attr, nextAttr);
      }
    }
  });
}
